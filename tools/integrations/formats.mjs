/** Deterministic native strings and Markdown metadata; prevents invalid agent configuration.
 * Imported by the integration adapters. Needs only Node built-ins.
 */
export const generated = '<!-- GENERATED by scripts/render-integrations.mjs; do not edit by hand; edit .harness/ source. -->'
export const generatedToml = '# GENERATED by scripts/render-integrations.mjs; do not edit by hand; edit .harness/ source.\n'

// JSON basic strings are also TOML basic strings and YAML double-quoted scalars.
export const quote = (value) => JSON.stringify(value)
export const json = (value) => JSON.stringify(value, null, 2) + '\n'
export const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** Shared agent metadata uses name and description as single-line YAML string scalars. */
export function markdown(source, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)([\s\S]*)$/.exec(source)
  if (!match) throw new Error('Missing Markdown frontmatter: ' + file)
  const fields = {}
  for (const line of match[1].split(/\r?\n/)) {
    const field = /^([a-z-]+):\s+(.+)$/.exec(line)
    if (!field || Object.hasOwn(fields, field[1])) throw new Error('Invalid frontmatter: ' + file)
    const scalar = field[2].trim()
    if (/^[>|]/.test(scalar)) throw new Error('Use single-line metadata strings: ' + file)
    fields[field[1]] = scalar.startsWith('"')
      ? JSON.parse(scalar)
      : scalar.startsWith("'") && scalar.endsWith("'")
        ? scalar.slice(1, -1).replaceAll("''", "'")
        : scalar
  }
  if (!/^[a-z][a-z0-9-]*$/.test(fields.name ?? '') || typeof fields.description !== 'string' || !fields.description.trim()) {
    throw new Error('Invalid name or description: ' + file)
  }
  return { ...fields, header: match[1], body: match[2].trimStart() }
}

export function generatedMarkdown(source, file) {
  const { header, body } = markdown(source, file)
  return '---\n' + header + '\n---\n\n' + generated + '\n\n' + body
}
